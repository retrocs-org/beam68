#!/usr/bin/env python3
"""Build Beam68's localisation from catalogs/<Name>.cd and <Name>.<lang>.ct.

    make-catalog.py           regenerate everything
    make-catalog.py --check   fail if anything is out of date or invalid

One catalog per program: Beam68.cd (launcher, MSG_*) and Beam68Prefs.cd
(Preferences, PMSG_*).  For each <Name>.cd the outputs are:
  include/<name>_strings.h        identifiers
  src/<name>_strings.c            built-in English strings
  catalogs/<language>/<Name>.catalog   IFF CTLG catalogs for locale.library

The .cd/.ct files use the standard CatComp/FlexCat layout, so translators
can also use those tools.  In this repository .ct files are UTF-8; the
catalogs are written in ISO-8859-1 (codeset 0), the Amiga character set.
Every translation must keep the original's printf placeholders in order.
"""
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CAT = ROOT / "catalogs"
VERSION = (ROOT / "VERSION").read_text(encoding="ascii").strip()
DATE = "27.10.2026"
PLACEHOLDER = re.compile(r"%[-+ 0#]*[0-9]*(?:\.[0-9]+)?l?[dusxXc%]")


def unescape(text):
    out, i = [], 0
    while i < len(text):
        if text[i] == "\\" and i + 1 < len(text):
            nxt = text[i + 1]
            out.append({"n": "\n", "t": "\t", "\\": "\\"}.get(nxt, "\\" + nxt))
            i += 2
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def read_cd(path):
    entries, lines = [], path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if not line.strip() or line.startswith(";") or line.startswith("#"):
            continue
        m = re.match(r"^([A-Z][A-Z0-9_]*)\s*\((\d+)//\)\s*$", line)
        if not m:
            raise SystemExit("%s: bad line: %r" % (path.name, line))
        entries.append((m.group(1), int(m.group(2)), unescape(lines[i])))
        i += 1
    ids = [e[1] for e in entries]
    if ids != list(range(1, len(ids) + 1)):
        raise SystemExit("%s: IDs must be 1..n in order" % path.name)
    return entries


def read_ct(path):
    header, strings, lines = {}, {}, path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if line.startswith("##"):
            key, _, value = line[2:].strip().partition(" ")
            header[key] = value.strip()
        elif re.match(r"^[A-Z][A-Z0-9_]*$", line):
            strings[line] = unescape(lines[i])
            i += 1
    return header, strings


def c_literal(text):
    out = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + out + '"'


def header_text(base, entries):
    low, up = base.lower(), base.upper()
    rows = ["/* Generated by scripts/make-catalog.py from catalogs/%s.cd." % base,
            " * Do not edit; change the .cd file and regenerate. */",
            "#ifndef %s_STRINGS_H" % up, "#define %s_STRINGS_H" % up, ""]
    rows += ["#define %s %d" % (name, ident) for name, ident, _ in entries]
    rows += ["", "#define %s_STRING_COUNT %d" % (up, len(entries)),
             "extern const char *const %s_strings[%s_STRING_COUNT];" % (low, up),
             "#endif", ""]
    return "\n".join(rows)


def source_text(base, entries):
    low, up = base.lower(), base.upper()
    rows = ["/* Generated by scripts/make-catalog.py from catalogs/%s.cd." % base,
            " * Built-in English strings, indexed by identifier - 1. */",
            '#include "%s_strings.h"' % low, "",
            "const char *const %s_strings[%s_STRING_COUNT]={" % (low, up)]
    rows += ["    %s, /* %s */" % (c_literal(text), name) for name, _, text in entries]
    rows += ["};", ""]
    return "\n".join(rows)


def iff_chunk(tag, data):
    return tag + struct.pack(">I", len(data)) + data + (b"\0" if len(data) % 2 else b"")


def catalog_bytes(base, language, entries, strings):
    strs = bytearray()
    for name, ident, _ in entries:
        if name not in strings:
            continue  # missing translations fall back to the built-in text
        raw = strings[name].encode("latin-1") + b"\0"
        strs += struct.pack(">II", ident, len(raw)) + raw + b"\0" * ((4 - len(raw) % 4) % 4)
    fver = ("$VER: %s.catalog %s (%s)" % (base, VERSION, DATE)).encode("ascii") + b"\0"
    body = b"CTLG" + iff_chunk(b"FVER", fver) + \
        iff_chunk(b"LANG", language.encode("ascii") + b"\0") + iff_chunk(b"STRS", bytes(strs))
    return b"FORM" + struct.pack(">I", len(body)) + body


def build():
    errors, outputs = [], {}
    for cd in sorted(CAT.glob("*.cd")):
        base = cd.stem
        entries = read_cd(cd)
        outputs[ROOT / "include" / ("%s_strings.h" % base.lower())] = header_text(base, entries).encode("ascii")
        outputs[ROOT / "src" / ("%s_strings.c" % base.lower())] = source_text(base, entries).encode("ascii")
        known = {name: text for name, _, text in entries}
        for ct in sorted(CAT.glob("%s.*.ct" % base)):
            header, strings = read_ct(ct)
            language = header.get("language", "")
            if not language:
                errors.append("%s: missing '## language'" % ct.name)
                continue
            before = len(errors)
            for name, text in strings.items():
                if name not in known:
                    errors.append("%s: unknown %s" % (ct.name, name))
                elif PLACEHOLDER.findall(text) != PLACEHOLDER.findall(known[name]):
                    errors.append("%s: %s placeholders differ from the original" % (ct.name, name))
                else:
                    try:
                        text.encode("latin-1")
                    except UnicodeEncodeError:
                        errors.append("%s: %s is not ISO-8859-1" % (ct.name, name))
            missing = [n for n in known if n not in strings]
            if missing:
                print("note: %s lacks %d string(s), English is used: %s" %
                      (ct.name, len(missing), ", ".join(missing[:5])), file=sys.stderr)
            if len(errors) == before:
                outputs[CAT / language / ("%s.catalog" % base)] = catalog_bytes(base, language, entries, strings)
    return outputs, errors


def main():
    check = "--check" in sys.argv[1:]
    outputs, errors = build()
    for message in errors:
        print("error: " + message, file=sys.stderr)
    if errors:
        return 1
    stale = [p for p, data in outputs.items() if not p.exists() or p.read_bytes() != data]
    if check:
        for path in stale:
            print("out of date: %s (run scripts/make-catalog.py)" % path.relative_to(ROOT), file=sys.stderr)
        return 1 if stale else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(outputs[path])
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
